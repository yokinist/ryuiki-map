import { describe, expect, it } from "vitest";
import { type SearchRow, searchPlaces } from "./place-search";

const cities = {
  "08232": ["茨城県", "神栖市"],
  "08229": ["茨城県", "行方市"],
  "12202": ["千葉県", "銚子市"],
  "13219": ["東京都", "狛江市"],
  "12101": ["千葉県", "千葉市中央区"],
  "22209": ["静岡県", "島田市"],
} as Record<string, [string, string]>;
const rows: SearchRow[] = [
  [13219, "", 139.5786, 35.6348],
  [13219, "和泉本町", 139.5786, 35.6348],
  [12202, "", 140.8266, 35.7347],
  [12202, "本町", 140.8285, 35.7353],
  [12202, "犬吠埼", 140.8636, 35.7079],
  [8229, "阿波崎", 140.4203, 35.9521],
  [8232, "波崎東部東町", 140.8414, 35.742],
  [8232, "大字波崎", 140.8095, 35.7414],
  [22209, "千葉", 138.1544, 34.8647],
  [12101, "", 140.1233, 35.6074],
];
const labels = (q: string) => searchPlaces(rows, cities, q).map((h) => h.label);

describe("searchPlaces", () => {
  it("市区町村の名前で、その市区町村と位置が出る", () => {
    expect(searchPlaces(rows, cities, "狛江")[0]).toEqual({
      label: "東京都狛江市",
      p: [139.5786, 35.6348],
      aza: false,
    });
  });

  it("町丁・字は、名前が同じ → 名前で始まる → 名前に含む の順。頭の「大字」は外して比べ、出す", () => {
    expect(labels("波崎")).toEqual([
      "茨城県神栖市 波崎",
      "茨城県神栖市 波崎東部東町",
      "茨城県行方市 阿波崎",
    ]);
  });

  it("市区町村の名前に合っても、その中の町丁・字は名前に合うものだけ出す", () => {
    expect(labels("銚子")).toEqual(["千葉県銚子市"]);
  });

  it("名前で始まる市区町村は、名前が同じ町丁・字より先に出す", () => {
    expect(labels("千葉")).toEqual(["千葉県千葉市中央区", "静岡県島田市 千葉"]);
  });

  it("空白で区切ると、最後の語は町丁・字の名前に、ほかの語は都道府県・市区町村に合うものを出す", () => {
    expect(labels("銚子　本町")).toEqual(["千葉県銚子市 本町"]);
  });

  it("空の検索語では何も出さない", () => {
    expect(labels(" ")).toEqual([]);
  });
});
